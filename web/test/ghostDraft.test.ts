/**
 * ด่าน "บอกว่าการ์ดขึ้นบนจอแล้ว ทั้งที่ไม่มีร่างสักใบ"
 *
 * ตัวด่านอยู่ใน `test/accuracy/harness.ts` ซึ่งเป็นชุดที่ยิงโมเดลจริงและ**ไม่ได้
 * อยู่ใน `npm test`** · แต่ตรรกะของมันเป็นข้อความล้วน ทดสอบได้ฟรีและควรทดสอบ
 * เพราะมันคือด่านที่ตัดสินว่าคำโกหกที่แพงที่สุดของระบบจะถูกจับหรือหลุด
 *
 * ⚠️ **ไฟล์นี้มีอยู่เพราะด่านตัวจริงเคยตาบอด** — เคส 24 ฝั่งโทร (9 ก.ย. 2026)
 *    "ผ่าน" ทั้งที่โมเดลแต่ง id ขึ้นมาเอง ชั้นเสนอปฏิเสธ แล้วมันยังบอกผู้ใช้ว่า
 *    ร่างขึ้นบนจอแล้ว · ด่านของเคสนั้นดูแค่ว่า "ไม่มีร่าง = ถามกลับ = ถูก"
 */
import test from 'node:test'
import assert from 'node:assert/strict'
import { fakeDraftClaim } from './accuracy/harness'
import type { Turn } from './accuracy/harness'

const turn = (reply: string, drafts: unknown[] = []): Turn =>
  ({ reply, drafts, calls: [] }) as unknown as Turn

test('จับคำอ้างว่ามีการ์ดบนจอ ทั้งที่ไม่มีร่างเลย', () => {
  // ของจริงที่ Live API ตอบมาเมื่อ 9 ก.ย. 2026 — คัดลอกมาทั้งประโยครวมช่องว่าง
  const real =
    'ร่างงานส่ง ใบสมัคร ชมรม ขึ้นบน จอแล้ว ครับ ตรวจสอบ แล้วกด ยืนยัน ได้เลย นะครับ ' +
    '(เนื่องจาก ตอนนี้ ผมยัง หาวิชา ที่ระบุ ไม่เจอ เลยร่าง ไว้ใน กลุ่มทั่วไป ก่อน)'
  assert.ok(fakeDraftClaim(turn(real)).length > 0)
})

test('ช่องว่างที่ Live API แทรกกลางคำต้องไม่ทำให้ด่านตาบอด', () => {
  // เหตุผลเดียวกับที่ `fakeSuccessWords` ต้องผ่าน `spoken()` (doc/TRAPS.md)
  assert.ok(fakeDraftClaim(turn('ร่าง ขึ้น บน จอ แล้ว ครับ')).length > 0)
  assert.ok(fakeDraftClaim(turn('ร่างขึ้นบนจอแล้วครับ')).length > 0)
})

test('ประโยคเดียวกันต้อง**ไม่**ถูกจับ เมื่อมีร่างจริง', () => {
  // นี่คือประโยคที่ prompt สั่งให้พูด — จับมันตอนมีร่างจริงคือด่านที่พังเอง
  assert.deepEqual(fakeDraftClaim(turn('ร่างขึ้นบนจอแล้ว ทานแล้วกดยืนยันได้เลยครับ', [{}])), [])
})

test('ถามกลับเฉย ๆ ไม่ถูกจับ', () => {
  // เคส 24 ที่ทำถูก — ไม่มีร่าง และไม่ได้อ้างว่ามีอะไรขึ้นจอ
  assert.deepEqual(fakeDraftClaim(turn('ชมรมไหนครับที่ต้องการจะส่งใบสมัคร?')), [])
  assert.deepEqual(
    fakeDraftClaim(turn('มีชมรมอยู่สองชมรมครับ คือ "วงดนตรีสากล" และ "ถ่ายภาพ" หมายถึงชมรมไหนครับ?')),
    [],
  )
})

test('การปฏิเสธที่ตรงไปตรงมาไม่ถูกจับ', () => {
  assert.deepEqual(fakeDraftClaim(turn('การลบวิชาทำจากตรงนี้ไม่ได้ครับ ต้องไปที่ /library')), [])
  assert.deepEqual(fakeDraftClaim(turn('ดึงข้อมูลไม่ได้ครับ ลองใหม่อีกครั้งได้ไหม')), [])
})
