  // ถ้าไม่สั่ง มันจะอ่านกระดานให้ฟังเฉย ๆ แล้วจบ ซึ่งเป็นงานที่ผู้ใช้ทำเองได้อยู่แล้ว
  // เหตุผลทั้งหมดที่ทำฟีเจอร์นี้คือ **ถ่ายแล้วได้การ์ดให้กดยืนยัน**
