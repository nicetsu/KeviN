import test from 'node:test'
import assert from 'node:assert/strict'
import { orderEvents, isPastEvent } from '../lib/eventOrder'

const NOW = '2026-09-01T12:00:00.000Z'

const ev = (id: string, starts: string, ends: string) => ({ id, starts_at: starts, ends_at: ends })

test('วัดที่ ends_at ไม่ใช่ starts_at', () => {
  // ค่ายสามวันที่เริ่มไปแล้วแต่ยังไม่จบ ต้องนับว่ายังไม่ผ่าน
  const running = ev('a', '2026-08-30T00:00:00.000Z', '2026-09-03T00:00:00.000Z')
  assert.equal(isPastEvent(running, NOW), false)
})

test('จบพอดีตอนนี้ยังไม่นับว่าผ่าน', () => {
  assert.equal(isPastEvent(ev('a', NOW, NOW), NOW), false)
})

test('ที่ผ่านแล้วร่วงไปท้าย', () => {
  const rows = [
    ev('เก่า', '2026-08-01T00:00:00.000Z', '2026-08-01T03:00:00.000Z'),
    ev('ใหม่', '2026-09-10T00:00:00.000Z', '2026-09-10T03:00:00.000Z'),
  ]
  assert.deepEqual(orderEvents(rows, NOW).map((e) => e.id), ['ใหม่', 'เก่า'])
})

test('ที่ยังไม่ผ่านเรียงจากใกล้ที่สุดก่อน', () => {
  const rows = [
    ev('ไกล', '2026-10-01T00:00:00.000Z', '2026-10-01T03:00:00.000Z'),
    ev('ใกล้', '2026-09-02T00:00:00.000Z', '2026-09-02T03:00:00.000Z'),
  ]
  assert.deepEqual(orderEvents(rows, NOW).map((e) => e.id), ['ใกล้', 'ไกล'])
})

test('ที่ผ่านแล้วเรียงกลับทาง — ล่าสุดอยู่บน', () => {
  // ไล่จากบนลงล่างต้องได้ "ใกล้ปัจจุบันที่สุด" ตลอด ไม่กระโดดตรงรอยต่อ
  const rows = [
    ev('นานมาก', '2026-06-01T00:00:00.000Z', '2026-06-01T03:00:00.000Z'),
    ev('เมื่อวาน', '2026-08-31T00:00:00.000Z', '2026-08-31T03:00:00.000Z'),
  ]
  assert.deepEqual(orderEvents(rows, NOW).map((e) => e.id), ['เมื่อวาน', 'นานมาก'])
})

test('ทั้งกลุ่มไล่จากใกล้ปัจจุบันออกไปสองทาง', () => {
  const rows = [
    ev('นานมาก', '2026-06-01T00:00:00.000Z', '2026-06-01T03:00:00.000Z'),
    ev('ไกล', '2026-10-01T00:00:00.000Z', '2026-10-01T03:00:00.000Z'),
    ev('เมื่อวาน', '2026-08-31T00:00:00.000Z', '2026-08-31T03:00:00.000Z'),
    ev('พรุ่งนี้', '2026-09-02T00:00:00.000Z', '2026-09-02T03:00:00.000Z'),
  ]
  assert.deepEqual(
    orderEvents(rows, NOW).map((e) => e.id),
    ['พรุ่งนี้', 'ไกล', 'เมื่อวาน', 'นานมาก']
  )
})

test('ไม่แก้อาร์เรย์ต้นฉบับ', () => {
  const rows = [
    ev('เก่า', '2026-08-01T00:00:00.000Z', '2026-08-01T03:00:00.000Z'),
    ev('ใหม่', '2026-09-10T00:00:00.000Z', '2026-09-10T03:00:00.000Z'),
  ]
  orderEvents(rows, NOW)
  assert.deepEqual(rows.map((e) => e.id), ['เก่า', 'ใหม่'])
})

test('รายการว่างได้รายการว่าง', () => {
  assert.deepEqual(orderEvents([], NOW), [])
})
