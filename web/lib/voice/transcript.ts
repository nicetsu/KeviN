export type Turn = { role: 'user' | 'assistant'; content: string }

/** ข้อความที่ลงแทนสิ่งที่ผู้ใช้พูด */
export const VOICE_PLACEHOLDER = 'voice'

export function redactVoiceTurns(turns: readonly Turn[]): Turn[] {
  return turns.map((t) =>
    t.role === 'user' ? { role: 'user', content: VOICE_PLACEHOLDER } : t
  )
}
