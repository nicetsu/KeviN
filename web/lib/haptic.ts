'use client'

/**
 * สั่นสั้น ๆ ตอนทำอะไรสำเร็จ
 *
 * บนมือถือไม่มี hover ให้พึ่ง และการติ๊กงานเสร็จเป็นสิ่งที่ทำวันละหลายครั้ง
 * โดยไม่ได้มองจอเต็มตา — การสั่นสั้น ๆ ยืนยันได้โดยไม่ต้องอ่านอะไรเลย
 *
 * ⚠️ **iOS ไม่รองรับ `navigator.vibrate` เลย** และ Chrome ไม่ยอมสั่นถ้าผู้ใช้
 *    ยังไม่เคยแตะหน้านั้น · ทั้งสองกรณีเงียบไปเฉย ๆ ไม่ throw
 *    จึงไม่ต้องเช็คอะไรมากไปกว่าว่ามีฟังก์ชันนี้ไหม — และ**ห้ามให้มันพา
 *    การกระทำหลักล้มตาม** ถ้าสั่นไม่ได้ งานก็ต้องยังทำสำเร็จ
 */

/** สั้นมาก · ใช้ยืนยันการกระทำที่สำเร็จแล้ว เช่นติ๊กงานเสร็จ */
export function tap(): void {
  try {
    navigator.vibrate?.(10)
  } catch {
    /* เครื่องไม่รองรับก็ไม่เป็นไร */
  }
}

/**
 * สองจังหวะสั้น ๆ · ใช้กับของที่**หายไปจากจอ** เช่นเก็บเข้าคลัง
 *
 * ต่างจาก `tap()` เพราะสองอย่างนี้ต้องแยกออกจากกันได้ด้วยความรู้สึก —
 * ติ๊กเสร็จคือของยังอยู่ ส่วนเก็บเข้าคลังคือของหายไปแล้ว
 */
export function away(): void {
  try {
    navigator.vibrate?.([8, 40, 8])
  } catch {
    /* เครื่องไม่รองรับก็ไม่เป็นไร */
  }
}
