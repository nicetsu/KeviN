/**
 * ของที่เก็บเข้าคลังแล้วรอถูกลบถาวร
 *
 * ตั้งแต่ 1 ก.ย. 2026 ระบบเก็บของอัตโนมัติทุกคืนและลบถาวรเมื่อครบ 7 วัน
 * (`housekeeping()` ใน DB) แต่ไม่มีหน้าไหนมองเห็นช่วงเจ็ดวันนั้นเลย —
 * ของถูกเก็บและถูกลบโดยผู้ใช้ไม่มีโอกาสเห็น ซึ่งขัดหลัก "ไม่มีอะไรหายเงียบ ๆ"
 *
 * ⚠️ **ค่าคงที่ตัวนี้ต้องตรงกับ `purge_archived()` ใน DB เสมอ**
 *    ถ้าแก้ที่หนึ่งแล้วลืมอีกที่ หน้าจอจะนับถอยหลังผิดโดยไม่มีอะไรฟ้อง —
 *    ผู้ใช้จะเห็นว่า "เหลืออีก 2 วัน" แล้วของหายไปคืนนั้นเลย
 */

/** ต้องตรงกับ `interval '7 days'` ใน `purge_archived()` */
export const KEEP_DAYS = 7

const DAY_MS = 86_400_000

export type Archived = {
  /** ISO string · เวลาที่ถูกเก็บเข้าคลัง */
  archivedAt: string
  /** ระบบเก็บให้เองตอนตีสาม หรือผู้ใช้กดเก็บเอง */
  auto: boolean
}

/**
 * เหลืออีกกี่มิลลิวินาทีก่อนถูกลบ · ติดลบ = เลยกำหนดแล้ว รอบ cron ถัดไปจะพาไป
 *
 * ที่คืนเป็น ms ไม่ใช่วัน เพราะหน้าจอต้องแยก "อีก 4 ชั่วโมง" ออกจาก "อีก 6 วัน"
 * การปัดเป็นวันตั้งแต่ตรงนี้จะทำให้ของที่เหลือไม่ถึงวันดูเหมือนของที่เหลือทั้งวัน
 */
export function msLeft(a: Archived, now: number): number {
  return new Date(a.archivedAt).getTime() + KEEP_DAYS * DAY_MS - now
}

/**
 * คำบอกเวลาที่เหลือ · สั้นพอใส่ป้ายเล็กท้ายแถวได้
 *
 * ⚠️ ต่ำกว่าหนึ่งวันบอกเป็นชั่วโมง เพราะนั่นคือช่วงที่การกดคืนยังทันจริง ๆ
 *    "อีก 0 วัน" ไม่ได้บอกอะไรกับคนที่กำลังตัดสินใจว่าจะรีบไหม
 */
export function leftLabel(ms: number): string {
  if (ms <= 0) return 'ลบคืนนี้'
  const hours = Math.floor(ms / 3_600_000)
  if (hours < 24) return hours <= 1 ? 'อีกไม่ถึงชั่วโมง' : `อีก ${hours} ชม.`
  return `อีก ${Math.floor(hours / 24)} วัน`
}

/** เหลือน้อยกว่าหนึ่งวัน — แถวพวกนี้ต้องเด่นกว่าแถวอื่น */
export function isUrgent(ms: number): boolean {
  return ms < DAY_MS
}

export type Group = { key: 'urgent' | 'soon'; label: string; rows: number[] }

/**
 * แบ่งเป็นสองกลุ่มตามเวลาที่เหลือ **ไม่ใช่เวลาที่เก็บ**
 *
 * สิ่งที่ผู้ใช้เปิดหน้านี้มาถามคือ "อันไหนกำลังจะหาย" ไม่ใช่ "เก็บอันไหนไว้ตอนไหน"
 * การเรียงตามเวลาที่เก็บจะเอาของที่ปลอดภัยที่สุดขึ้นบนสุด ซึ่งกลับหัวกับคำถาม
 *
 * คืนเป็นดัชนีของอาร์เรย์ต้นทาง เพื่อให้ฝั่งเรียกเอาไปประกอบกับข้อมูลเต็มเองได้
 * โดยไฟล์นี้ไม่ต้องรู้จักรูปของแถวเลย
 */
export function groupByLeft(rows: readonly Archived[], now: number): Group[] {
  const withMs = rows.map((r, i) => ({ i, ms: msLeft(r, now) })).sort((a, b) => a.ms - b.ms)
  const urgent = withMs.filter((r) => isUrgent(r.ms)).map((r) => r.i)
  const soon = withMs.filter((r) => !isUrgent(r.ms)).map((r) => r.i)

  const out: Group[] = []
  if (urgent.length) out.push({ key: 'urgent', label: 'เหลืออีกไม่ถึงวัน', rows: urgent })
  if (soon.length) out.push({ key: 'soon', label: 'ยังมีเวลา', rows: soon })
  return out
}

/**
 * ใครเป็นคนเก็บ — ระบบเก็บให้ กับเรากดเก็บเอง คนละความหมาย
 *
 * ของที่ระบบเก็บให้คือของที่**หมดอายุไปเอง** ผู้ใช้อาจไม่เคยรู้ตัวว่ามันหายไป
 * ส่วนของที่กดเก็บเองคือของที่**ตั้งใจทิ้ง** · แยกให้เห็นเพราะสองอย่างนี้
 * ต้องการความสนใจไม่เท่ากันตอนตัดสินใจว่าจะกดคืนไหม
 */
export function byWhom(auto: boolean): string {
  return auto ? 'ระบบเก็บให้' : 'คุณกดเก็บเอง'
}
